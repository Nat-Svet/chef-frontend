// вытеснены новыми рецептами — удаляем из базы при повторном запуске
const RETIRED_TITLES = ['Чечевичный крем-суп', 'Салат с кальмаром и яйцом', 'Суп-пюре из брокколи'];

// Длинные .in(...) со списком кириллических значений упираются в лимит длины URL
// и молча не срабатывают — всегда режем на пачки и проверяем ошибки.
const chunks = <T,>(items: T[], size: number): T[][] =>
  Array.from({ length: Math.ceil(items.length / size) }, (_, i) => items.slice(i * size, i * size + size));

const MEAT = /(филе|курин|бёдр|крыл|фарш|говяд|свинин|индейк|ветчин|сосиск|лосос|сёмг|тунец|треск|минтай|кальмар|креветк)/i;
const isMeat = (name: string) => name !== 'Яйцо куриное' && MEAT.test(name);
const round1 = (n: number) => Math.round(n * 10) / 10;

function build() {
  const unknown = new Set<string>();
  const recipes = R.map(([title, meal, equipment, flags, minutes, steps, ings]) => {
    let kcal = 0;
    let fat = 0;
    for (const [name, grams] of ings) {
      const m = MACROS[name];
      if (!m) {
        unknown.add(name);
        continue;
      }
      kcal += (m[0] * grams) / 100;
      fat += (m[2] * grams) / 100;
    }
    const tags = [
      ...(flags.includes('p') ? ['ПП'] : []),
      ...(flags.includes('s') ? ['Сытное'] : []),
      ...(flags.includes('f') ? ['Семейное'] : []),
      ...(ings.some(([n]) => isMeat(n)) ? [] : ['Вегетарианское']),
      ...(minutes <= 20 ? ['Быстро'] : []),
      ...(kcal <= 380 && fat <= 14 ? ['Низкокалорийное'] : []),
      ...equipment,
    ];
    return { title, meal, minutes, steps: steps.split('|'), ings, tags };
  });
  if (unknown.size) throw new Error('Нет КБЖУ для: ' + [...unknown].join(', '));
  return recipes;
}

async function main() {
  const recipes = build();
  const counts = { завтрак: 0, обед: 0, ужин: 0 } as Record<Meal, number>;
  recipes.forEach((r) => (counts[r.meal] += 1));
  console.log('К загрузке:', recipes.length, counts);

  const names = Object.keys(NEW_PRODUCTS);
  const skus = names.flatMap((n) => [`SMKT-${n}`, `VVILL-${n}`]);
  for (const part of chunks(skus, 10)) {
    const { error } = await supabase.from('store_products').delete().in('sku_id', part);
    if (error) throw error;
  }
  const productRows = names.flatMap((n) => {
    const [pack, smkt, vvill] = NEW_PRODUCTS[n];
    return [
      { store_name: 'Самокат', search_term: n, product_title: `${n} ${pack} г`, price: smkt, sku_id: `SMKT-${n}`, pack_weight_grams: pack, in_stock: true },
      { store_name: 'ВкусВилл', search_term: n, product_title: `${n} ${pack} г (ВВ)`, price: vvill, sku_id: `VVILL-${n}`, pack_weight_grams: pack, in_stock: true },
    ];
  });
  const { error: pError } = await supabase.from('store_products').insert(productRows);
  if (pError) throw pError;

  const titles = [...recipes.map((r) => r.title), ...RETIRED_TITLES];
  const oldIds: number[] = [];
  for (const part of chunks(titles, 8)) {
    const { data, error } = await supabase.from('recipes').select('id').in('title', part);
    if (error) throw error;
    oldIds.push(...(data ?? []).map((r) => r.id));
  }
  for (const part of chunks(oldIds, 25)) {
    const { error: e1 } = await supabase.from('recipe_ingredients').delete().in('recipe_id', part);
    if (e1) throw e1;
    const { error: e2 } = await supabase.from('recipes').delete().in('id', part);
    if (e2) throw e2;
  }

  let ingredients = 0;
  for (const r of recipes) {
    const { data, error } = await supabase
      .from('recipes')
      .insert({
        title: r.title,
        instructions: r.steps.map((s, i) => `${i + 1}. ${s}`).join('\n'),
        image_url: null,
        cooking_time: r.minutes,
        meal_type: r.meal,
        tags: r.tags,
      })
      .select('id')
      .single();
    if (error || !data) throw error ?? new Error(`Не создан рецепт ${r.title}`);

    const rows = r.ings.map(([name, grams]) => {
      const m = MACROS[name];
      const k = grams / 100;
      return {
        recipe_id: data.id,
        name,
        amount_grams: grams,
        kcal: round1(m[0] * k),
        protein: round1(m[1] * k),
        fat: round1(m[2] * k),
        carb: round1(m[3] * k),
      };
    });
    const { error: iError } = await supabase.from('recipe_ingredients').insert(rows);
    if (iError) throw iError;
    ingredients += rows.length;
  }

  console.log(`Новых товаров: ${productRows.length} | рецептов: ${recipes.length} | ингредиентов: ${ingredients}`);
}

main().catch((error) => {
  console.error('Сид не удался:', error);
  process.exit(1);
});
